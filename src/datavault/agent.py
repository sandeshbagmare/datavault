"""LangGraph agent — orchestrates the DataVault tools with privacy-first data handling.

The agent uses LangGraph's state machine to manage conversations, bind the
3 atomic tools, and ensure the LLM only ever sees Data Profiles.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from collections.abc import Sequence
from typing import Annotated, Any, Literal, TypedDict

from dotenv import load_dotenv
from langchain_core.messages import AIMessage, BaseMessage, HumanMessage, SystemMessage
from langgraph.graph import END, StateGraph
from langgraph.graph.message import add_messages
from langgraph.prebuilt import ToolNode

from datavault.context import DataContext, Policy
from datavault.proxy.interceptor import DataProxyInterceptor
from datavault.tools import create_tools

# Load environment variables
load_dotenv()


class AgentState(TypedDict):
    """State schema for the DataVault agent.

    Attributes:
        messages: Conversation history with add_messages reducer.
        data_refs: List of active data reference IDs.
        generated_files: List of file paths generated by tools.
    """

    messages: Annotated[Sequence[BaseMessage], add_messages]
    data_refs: list[str]
    generated_files: list[str]


# System prompt that instructs the LLM how to use the tools
SYSTEM_PROMPT = """You are DataVault, a privacy-first data analysis assistant.

You have access to these tools:
1. **profile_and_filter** — Explore data. Filter, project, group, aggregate, sort and limit a data reference; returns a bounded Data Profile (schema, stats, a few sample rows) and a NEW reference id for the result. Use it to verify column names and to read exact top/bottom answers (order_by + limit).
2. **generate_html_viz** — Build ANY interactive HTML visualization or dashboard. Pass a declarative `spec` (datasets + nested blocks: grid/row/tabs/kpis/chart/table/text/markdown, any theme, any Plotly chart via `figure`), or the quick arguments (`chart_type`, `x_col`, `charts`, `kpis`, ...). If the request needs something blocks cannot express (custom interaction, d3, bespoke SVG), supply `custom_html` / `js` / `css` with `datasets` for server-computed data.
3. **generate_markdown** — Build ANY Markdown document from ordered `sections` bound to computed datasets (or the quick summary/breakdown/trend reports).

## How you work:
- You NEVER see the full data. You only see Data Profiles (schema, statistics, a few bounded sample rows). Numbers shown to the user are computed server-side from the reference you name, so you describe WHAT to show, never the data itself.
- When asked to analyze data, first use `profile_and_filter` to understand the dataset and verify column names. Never invent column names.
- Follow the user's request exactly: their theme, layout, chart types, sections, wording. Do not fall back to a generic dashboard when they asked for something specific. Anything they ask for can be built: compose it from blocks, use a native Plotly `figure`, or, if needed, custom code.
- Aggregate large data in datasets (group_by/metrics/limit) instead of plotting raw rows.
- Use reference IDs (e.g. "ref_abc123" or "vehicle_sales") when calling tools; derived results get new reference ids.
- If a tool returns an Error, read it, fix the spec, and retry.

Be helpful, concise, and explain the key business takeaways."""


def _get_llm(
    provider: str | None = None,
    model: str | None = None,
    api_key: str | None = None,
    base_url: str | None = None,
) -> Any:
    """Create an LLM instance based on the configured provider.

    Supports:
    - Standard providers: OpenAI, Google, Anthropic
    - Commercial OpenAI-compatible providers: OpenRouter, Groq, DeepSeek, Together, Mistral, etc.
    - Local / Self-hosted providers: Ollama, vLLM, LM Studio, LocalAI
    - Any custom API endpoint supplying a custom api_base / base_url and api_key

    Args:
        provider: Provider name (e.g. openai, google, anthropic, openrouter, groq, deepseek, ollama, custom).
        model: Model identifier.
        api_key: Optional API key override.
        base_url: Optional API base URL override (e.g. https://openrouter.ai/api/v1).

    Returns:
        A LangChain chat model instance with tool calling support.
    """
    # 1. Resolve base_url / api_base
    base_url = (
        base_url
        or os.getenv("LLM_BASE_URL")
        or os.getenv("API_BASE")
        or os.getenv("OPENAI_API_BASE")
        or os.getenv("OPENAI_BASE_URL")
        or os.getenv("BASE_URL")
    )
    if base_url:
        base_url = base_url.strip()

    # 2. Resolve provider
    raw_provider = provider or os.getenv("LLM_PROVIDER")
    if raw_provider:
        p = raw_provider.lower().strip()
    else:
        # Auto-detect if provider not explicitly specified
        if os.getenv("GOOGLE_API_KEY") or os.getenv("GEMINI_API_KEY"):
            p = "google"
        elif os.getenv("ANTHROPIC_API_KEY"):
            p = "anthropic"
        else:
            p = "openai"

    # Well-known provider default endpoints
    provider_presets = {
        "openrouter": "https://openrouter.ai/api/v1",
        "groq": "https://api.groq.com/openai/v1",
        "deepseek": "https://api.deepseek.com/v1",
        "ollama": "http://localhost:11434/v1",
        "together": "https://api.together.xyz/v1",
        "vllm": "http://localhost:8000/v1",
        "lmstudio": "http://localhost:1234/v1",
        "lm-studio": "http://localhost:1234/v1",
        "localai": "http://localhost:8080/v1",
        "mistral": "https://api.mistral.ai/v1",
        "cerebras": "https://api.cerebras.ai/v1",
        "fireworks": "https://api.fireworks.ai/inference/v1",
    }

    if p in provider_presets:
        if not base_url:
            base_url = provider_presets[p]
        p = "openai"  # All these presets speak OpenAI-compatible protocol

    # 3. Resolve model
    if not model:
        model = os.getenv("LLM_MODEL")
        if not model:
            if p in ("google", "gemini"):
                model = "gemini-2.0-flash"
            elif p in ("anthropic", "claude"):
                model = "claude-3-5-sonnet-20241022"
            else:
                model = "gpt-4o"

    # 4. Resolve api_key
    if not api_key:
        api_key = os.getenv("LLM_API_KEY") or os.getenv("API_KEY")
        if not api_key:
            if p in ("google", "gemini"):
                api_key = os.getenv("GOOGLE_API_KEY") or os.getenv("GEMINI_API_KEY")
            elif p in ("anthropic", "claude"):
                api_key = os.getenv("ANTHROPIC_API_KEY")
            else:
                api_key = (
                    os.getenv("OPENAI_API_KEY")
                    or os.getenv("OPENROUTER_API_KEY")
                    or os.getenv("GROQ_API_KEY")
                    or os.getenv("DEEPSEEK_API_KEY")
                )

    # 5. Instantiate Chat Model
    if p in ("google", "gemini"):
        from langchain_google_genai import ChatGoogleGenerativeAI

        kwargs: dict[str, Any] = {"model": model, "temperature": 0}
        if api_key:
            kwargs["google_api_key"] = api_key
        if base_url:
            kwargs["base_url"] = base_url
        return ChatGoogleGenerativeAI(**kwargs)

    elif p in ("anthropic", "claude"):
        from langchain_anthropic import ChatAnthropic

        kwargs = {"model": model, "temperature": 0}
        if api_key:
            kwargs["api_key"] = api_key
        if base_url:
            kwargs["base_url"] = base_url
        return ChatAnthropic(**kwargs)

    else:
        # Default to OpenAI or any OpenAI-compatible custom endpoint (OpenRouter, Groq, Ollama, DeepSeek, vLLM, etc.)
        from langchain_openai import ChatOpenAI

        kwargs = {"model": model, "temperature": 0}
        if api_key:
            kwargs["api_key"] = api_key
        elif base_url:
            # Local endpoints like Ollama / vLLM often don't mandate an API key
            kwargs["api_key"] = "not-needed"
        if base_url:
            kwargs["base_url"] = base_url
        return ChatOpenAI(**kwargs)


def create_agent(
    parquet_path: str | Path | None = None,
    provider: str | None = None,
    model: str | None = None,
    api_key: str | None = None,
    base_url: str | None = None,
    output_dir: str | Path = "output",
) -> tuple[Any, DataProxyInterceptor, Any]:
    """Create and configure the DataVault LangGraph agent.

    This is the main entry point for the DataVault agent. It:
    1. Sets up the DuckDB-backed DataProxyInterceptor
    2. Configures the 3 atomic tools
    3. Builds the LangGraph state machine
    4. Optionally registers a Parquet file as initial data

    Args:
        parquet_path: Path to a Parquet file to register as initial data.
        provider: LLM provider (openai, google, anthropic, openrouter, groq, deepseek, ollama, or custom).
        model: LLM model name.
        api_key: Optional API key override.
        base_url: Optional API base URL override (api_base / endpoint).
        output_dir: Base directory for generated outputs.

    Returns:
        A tuple of (compiled_graph, interceptor, initial_profile).
        The interceptor is returned so callers can register additional data sources.
    """
    # 1. Set up the privacy engine
    interceptor = DataProxyInterceptor()

    # 2. One isolated context per agent; the tools only see this context
    ctx = DataContext(
        connection=interceptor.connection,
        store=interceptor.data_store,
        profiler=interceptor.profiler,
        policy=Policy.from_env(),
        output_dir=output_dir,
    )

    # 3. Collect tools
    tools = create_tools(ctx)

    # 4. Create LLM with tools bound
    llm = _get_llm(provider=provider, model=model, api_key=api_key, base_url=base_url)
    llm_with_tools = llm.bind_tools(tools)

    # 5. Build the graph
    def agent_node(state: AgentState) -> dict[str, Any]:
        """The agent node — calls the LLM with the current messages."""
        messages = list(state["messages"])

        # Add system prompt if not already present
        if not messages or not isinstance(messages[0], SystemMessage):
            system_msg = SystemMessage(content=SYSTEM_PROMPT)
            # Add data reference context if available
            if state.get("data_refs"):
                refs_text = "\n".join(
                    f"- `{ref}`" for ref in state["data_refs"]
                )
                system_msg = SystemMessage(
                    content=SYSTEM_PROMPT + f"\n\n## Active Data References:\n{refs_text}"
                )
            messages = [system_msg] + messages

        response = llm_with_tools.invoke(messages)
        return {"messages": [response]}

    def should_continue(state: AgentState) -> Literal["tools", "end"]:
        """Determine whether to call tools or end the conversation."""
        last_message = state["messages"][-1]
        if isinstance(last_message, AIMessage) and last_message.tool_calls:
            return "tools"
        return "end"

    def tool_node_with_tracking(state: AgentState) -> dict[str, Any]:
        """Execute tools and track generated files and new data refs."""
        tool_node = ToolNode(tools)
        result = tool_node.invoke(state)

        # Track generated files and new references from tool outputs
        new_files: list[str] = list(state.get("generated_files", []))
        new_refs: list[str] = list(state.get("data_refs", []))

        for msg in result.get("messages", []):
            content = str(msg.content) if hasattr(msg, "content") else ""
            artifact = getattr(msg, "artifact", None)
            artifact = artifact if isinstance(artifact, dict) else {}
            path_part = artifact.get("path") or (
                content.split("saved to:")[-1].strip() if "saved to:" in content.lower() else None
            )
            if path_part and path_part not in new_files:
                new_files.append(path_part)
            found = [artifact.get("ref_id"), *artifact.get("ref_ids", [])] + re.findall(r"ref_[a-f0-9]{12}", content)
            for ref in found:
                if ref and ref not in new_refs:
                    new_refs.append(ref)

        result["generated_files"] = new_files
        result["data_refs"] = new_refs
        return result

    # Build the state graph
    graph = StateGraph(AgentState)
    graph.add_node("agent", agent_node)
    graph.add_node("tools", tool_node_with_tracking)
    graph.set_entry_point("agent")
    graph.add_conditional_edges("agent", should_continue, {"tools": "tools", "end": END})
    graph.add_edge("tools", "agent")

    compiled = graph.compile()

    # 6. Register initial data if provided
    initial_profile = None
    if parquet_path:
        parquet_path = Path(parquet_path)
        if parquet_path.exists():
            initial_profile = interceptor.register_parquet(
                str(parquet_path), "vehicle_sales"
            )

    return compiled, interceptor, initial_profile


def run_query(
    graph: Any,
    query: str,
    data_refs: list[str] | None = None,
    generated_files: list[str] | None = None,
) -> dict[str, Any]:
    """Run a single query through the agent.

    Args:
        graph: The compiled LangGraph state machine.
        query: The user's query string.
        data_refs: List of active data reference IDs.
        generated_files: List of previously generated files.

    Returns:
        The final agent state after processing.
    """
    initial_state: AgentState = {
        "messages": [HumanMessage(content=query)],
        "data_refs": data_refs or [],
        "generated_files": generated_files or [],
    }

    result = graph.invoke(initial_state)
    return result
